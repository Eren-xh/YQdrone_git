"""Evaluate a saved XH1 PPO policy, optionally in a MuJoCo viewer.

Examples (run from the drone_xh1 directory)::

    python evaluate_ppo.py --headless --episodes 20
    python evaluate_ppo.py --episodes 3

The policy and VecNormalize statistics must come from the same training run.
"""

from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

import mujoco
import numpy as np
from stable_baselines3 import PPO
from stable_baselines3.common.vec_env import DummyVecEnv, VecNormalize

from tasks.impact_recovery import ImpactRecoveryEnv
from debug_dashboard import DashboardServer, TelemetryHub, make_frame, session_metadata


PROJECT_ROOT = Path(__file__).resolve().parent
DEFAULT_MODEL = PROJECT_ROOT / "runs" / "xh1_ppo_bodyframe_fixed.zip"
DEFAULT_NORMALIZER = PROJECT_ROOT / "runs" / "xh1_ppo_bodyframe_fixed_vecnormalize.pkl"


def load_policy(model_path: Path, normalizer_path: Path):
    """Load PPO and the observation/reward normalization statistics."""
    if not model_path.exists():
        raise FileNotFoundError(f"PPO model not found: {model_path}")
    if not normalizer_path.exists():
        raise FileNotFoundError(
            "VecNormalize statistics not found: "
            f"{normalizer_path}\n"
            "Load the *_vecnormalize.pkl file generated by the same training run."
        )

    vec_env = DummyVecEnv([lambda: ImpactRecoveryEnv(render_mode=None)])
    vec_env = VecNormalize.load(str(normalizer_path), vec_env)
    # Evaluation must use the frozen training statistics and physical rewards.
    vec_env.training = False
    vec_env.norm_reward = False
    model = PPO.load(str(model_path), env=vec_env, device="cpu")
    return model, vec_env


def run_episode(
    model: PPO,
    vec_env: VecNormalize,
    episode_seed: int,
    viewer=None,
    realtime: bool = True,
    telemetry: TelemetryHub | None = None,
    episode_number: int = 1,
) -> dict:
    """Run one deterministic episode and return its summary."""
    vec_env.seed(episode_seed)
    obs = vec_env.reset()
    base_env = vec_env.venv.envs[0]
    control_dt = float(base_env.control_timestep)
    start_wall = time.perf_counter()
    next_wall = start_wall
    impact_reported = False
    max_rate = 0.0
    min_altitude = float("inf")
    last_info: dict = {}
    impact_step = None
    recovery_contact_steps = 0
    recovery_steps = 0
    episode_done = False
    reference_rotation = base_env._body_to_world().copy()
    steps = 0

    for step in range(base_env.max_episode_steps):
        if viewer is not None and not viewer.is_running():
            break

        # Capture what predict actually sees BEFORE stepping. On terminal
        # steps DummyVecEnv resets immediately, so post-step env reads would
        # otherwise show the next episode's sensors instead of this episode.
        if telemetry is not None:
            raw_obs = vec_env.get_original_obs()[0].copy()
            policy_obs = obs[0].copy()
            controller = "PPO" if base_env.phase == base_env.RECOVERY else "APPROACH"
        action, _ = model.predict(obs, deterministic=True)
        obs, reward, done, infos = vec_env.step(action)
        info = infos[0]
        steps = step + 1
        if telemetry is not None:
            telemetry.publish(make_frame(
                episode=episode_number, seed=episode_seed, step=steps,
                dt=control_dt, controller=controller, raw_obs=raw_obs,
                policy_obs=policy_obs, action=action[0].copy(), info=info,
                reward=float(reward[0]), done=bool(done[0]),
                reference_rotation=reference_rotation,
            ))
        last_info = info
        if info.get("phase") == base_env.RECOVERY:
            recovery_steps += 1
            recovery_contact_steps += int(bool(info.get("impact", False)))
        max_rate = max(max_rate, float(np.linalg.norm(info.get("angular_rate", [0, 0, 0]))))
        min_altitude = min(min_altitude, float(info.get("position", [0, 0, np.inf])[2]))

        if info.get("impact_seen") and not impact_reported:
            impact_reported = True
            impact_step = step
            print(
                f"  impact: step={step}, force={info.get('impact_force', 0.0):.4f} N, "
                f"impulse={info.get('impact_impulse', 0.0):.6f} N*s"
            )

        if viewer is not None:
            viewer.sync()

        if realtime:
            next_wall += control_dt
            sleep_time = next_wall - time.perf_counter()
            if sleep_time > 0.0:
                time.sleep(sleep_time)

        if bool(done[0]):
            episode_done = True
            break

    if last_info.get("recovered", False):
        end_reason = "recovered"
    elif last_info.get("crashed", False):
        end_reason = "ground_contact"
    elif last_info.get("TimeLimit.truncated", False):
        end_reason = "time_limit"
    else:
        end_reason = "viewer_closed" if not episode_done else "terminated"
    gravity = np.asarray(last_info.get("gravity_body", [0, 0, 1]))
    final_tilt_deg = float(np.degrees(np.arccos(np.clip(gravity[2], -1.0, 1.0))))

    return {
        "seed": episode_seed,
        "steps": steps,
        "impact_seen": bool(last_info.get("impact_seen", impact_reported)),
        "recovered": bool(last_info.get("recovered", False)),
        "crashed": bool(last_info.get("crashed", False)),
        "low_altitude": bool(last_info.get("low_altitude", False)),
        "ground_contact": bool(last_info.get("ground_contact", False)),
        "phase": last_info.get("phase", "UNKNOWN"),
        "end_reason": end_reason,
        "final_armor_contact": bool(last_info.get("impact", False)),
        "recovery_contact_fraction": recovery_contact_steps / max(recovery_steps, 1),
        "recovery_elapsed_s": int(last_info.get("recovery_steps", 0)) * control_dt,
        "impact_time_s": None if impact_step is None else (impact_step + 1) * control_dt,
        "final_position": np.asarray(last_info.get("position", [0, 0, 0])).tolist(),
        "final_tilt_deg": final_tilt_deg,
        "final_rate": float(np.linalg.norm(last_info.get("angular_rate", [0, 0, 0]))),
        "final_speed": float(np.linalg.norm(last_info.get("velocity_body", [0, 0, 0]))),
        "final_thrust": float(last_info.get("total_thrust", 0.0)),
        "max_rate": max_rate,
        "min_altitude": min_altitude,
        "reward": float(reward[0]) if "reward" in locals() else 0.0,
    }


def configure_viewer(
    viewer,
    lookat: np.ndarray,
    distance: float,
    azimuth: float,
    elevation: float,
) -> None:
    """Start with an external free camera so the whole impact is visible.

    ``mjCAMERA_FREE`` keeps the standard MuJoCo mouse controls enabled: drag
    to orbit/pan and use the mouse wheel to zoom. The XML ``flow_camera`` is
    intentionally not selected here because it is mounted close to the drone
    for a future optical-flow sensor.
    """
    viewer.cam.type = mujoco.mjtCamera.mjCAMERA_FREE
    viewer.cam.lookat[:] = np.asarray(lookat, dtype=np.float64)
    viewer.cam.distance = float(distance)
    viewer.cam.azimuth = float(azimuth)
    viewer.cam.elevation = float(elevation)
    try:
        viewer.opt.flags[mujoco.mjtVisFlag.mjVIS_CONTACTPOINT] = 1
        viewer.opt.flags[mujoco.mjtVisFlag.mjVIS_CONTACTFORCE] = 1
    except (AttributeError, IndexError):
        # Contact overlays vary slightly across MuJoCo Python versions.
        pass


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--model", type=Path, default=DEFAULT_MODEL)
    parser.add_argument("--vecnormalize", type=Path, default=DEFAULT_NORMALIZER)
    parser.add_argument("--episodes", type=int, default=1)
    parser.add_argument("--seed", type=int, default=100)
    parser.add_argument(
        "--camera-distance",
        type=float,
        default=1.8,
        help="initial free-camera distance in metres; mouse wheel still zooms",
    )
    parser.add_argument(
        "--camera-azimuth",
        type=float,
        default=90.0,
        help="initial free-camera azimuth in degrees",
    )
    parser.add_argument(
        "--camera-elevation",
        type=float,
        default=-15.0,
        help="initial free-camera elevation in degrees",
    )
    parser.add_argument("--lookat-x", type=float, default=0.40)
    parser.add_argument("--lookat-y", type=float, default=0.00)
    parser.add_argument("--lookat-z", type=float, default=0.50)
    parser.add_argument(
        "--headless",
        action="store_true",
        help="do not open a MuJoCo window; print evaluation statistics only",
    )
    parser.add_argument(
        "--no-realtime",
        action="store_true",
        help="run as fast as possible instead of synchronizing to 200 Hz control time",
    )
    parser.add_argument(
        "--dashboard", action=argparse.BooleanOptionalAction, default=True,
        help="serve a live PPO debug page and record every step (default: enabled)",
    )
    parser.add_argument("--dashboard-port", type=int, default=8765,
                        help="local web port; an occupied port falls back to a free port")
    parser.add_argument("--no-browser", action="store_true", help="print dashboard URL without opening a browser")
    parser.add_argument(
        "--dashboard-wait", action=argparse.BooleanOptionalAction, default=True,
        help="keep the web page available after evaluation in an interactive terminal",
    )
    parser.add_argument("--debug-dir", type=Path, default=PROJECT_ROOT / "runs" / "debug",
                        help="parent directory for complete JSONL telemetry recordings")
    args = parser.parse_args()
    if args.episodes <= 0:
        raise ValueError("--episodes must be positive")
    if not 0 <= args.dashboard_port <= 65535:
        raise ValueError("--dashboard-port must be between 0 and 65535")

    model, vec_env = load_policy(args.model.resolve(), args.vecnormalize.resolve())
    viewer = None
    telemetry = None
    dashboard = None
    run_status = "finished"
    run_message = ""
    try:
        if args.dashboard:
            base_env = vec_env.venv.envs[0]
            telemetry = TelemetryHub(session_metadata(
                args.model.resolve(), args.vecnormalize.resolve(), base_env,
                vec_env, args.episodes, args.seed,
            ), log_root=args.debug_dir)
            dashboard = DashboardServer(telemetry, args.dashboard_port)
            dashboard.start()
            if not args.no_browser:
                import webbrowser
                try:
                    webbrowser.open(dashboard.url)
                except webbrowser.Error:
                    print(f"Open the dashboard manually: {dashboard.url}")
        if not args.headless:
            try:
                import mujoco.viewer
            except ImportError as exc:
                raise RuntimeError(
                    "MuJoCo viewer is unavailable. Run with --headless or install "
                    "the MuJoCo viewer dependencies in the mujoco Conda environment."
                ) from exc

            base_env = vec_env.venv.envs[0]
            viewer = mujoco.viewer.launch_passive(base_env.model, base_env.data)
            configure_viewer(
                viewer,
                lookat=np.array([args.lookat_x, args.lookat_y, args.lookat_z]),
                distance=args.camera_distance,
                azimuth=args.camera_azimuth,
                elevation=args.camera_elevation,
            )

        summaries = []
        for episode in range(args.episodes):
            if viewer is not None and not viewer.is_running():
                break
            summary = run_episode(
                model,
                vec_env,
                args.seed + episode,
                viewer=viewer,
                realtime=not args.no_realtime,
                telemetry=telemetry,
                episode_number=episode + 1,
            )
            summaries.append(summary)
            if telemetry is not None:
                telemetry.add_summary({"episode": episode + 1, **summary})
            print(
                f"episode {episode + 1}: seed={summary['seed']} "
                f"phase={summary['phase']} impact={summary['impact_seen']} "
                f"recovered={summary['recovered']} crashed={summary['crashed']} "
                f"low_altitude={summary['low_altitude']} "
                f"ground_contact={summary['ground_contact']} "
                f"end={summary['end_reason']} "
                f"steps={summary['steps']} max_rate={summary['max_rate']:.3f} rad/s "
                f"min_z={summary['min_altitude']:.3f} m"
            )
            print(
                f"  final: tilt={summary['final_tilt_deg']:.2f} deg "
                f"rate={summary['final_rate']:.3f} rad/s "
                f"speed={summary['final_speed']:.3f} m/s "
                f"thrust={summary['final_thrust']:.3f} N "
                f"armor_contact={summary['final_armor_contact']} "
                f"recovery_contact={summary['recovery_contact_fraction']:.1%} "
                f"recovery_elapsed={summary['recovery_elapsed_s']:.3f} s"
            )

        if summaries:
            success = sum(item["recovered"] for item in summaries)
            print(f"success rate: {success}/{len(summaries)} = {success / len(summaries):.1%}")
    except KeyboardInterrupt:
        run_status, run_message = "interrupted", "评估被手动中断"
        print("Evaluation interrupted; recorded telemetry has been preserved.")
    except Exception as exc:
        run_status, run_message = "error", str(exc)
        raise
    finally:
        if viewer is not None:
            viewer.close()
        vec_env.close()
        if telemetry is not None:
            telemetry.finish(run_status, run_message)
        if dashboard is not None:
            try:
                if run_status == "finished" and args.dashboard_wait and sys.stdin.isatty():
                    print(f"Dashboard remains available for replay: {dashboard.url}")
                    print("Press Ctrl+C here to close the dashboard and return to the terminal.")
                    while True:
                        time.sleep(0.5)
            except KeyboardInterrupt:
                pass
            finally:
                dashboard.close()


if __name__ == "__main__":
    main()
